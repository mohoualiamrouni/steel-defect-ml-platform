"""Configuration for the ``steeldefect_ssl`` pipeline (P4).

Dataclass-backed YAML, mirroring the convention of ``defect_clustering/config.py``
and ``steeldefect_active_learning/config.py``: nested dataclasses, a strict
``load_config`` that rejects unknown keys (catches YAML typos), range
validation, and a ``fast_mode`` smoke override applied centrally.

Importing this module is cheap — it pulls in no torch / sklearn / spark, so it
can be used from tests and the Databricks dispatcher alike.
"""

from dataclasses import dataclass, field, fields, is_dataclass
from typing import Any, Dict, Optional, Tuple

try:  # pyyaml is in requirements.txt; degrade gracefully if ever absent
    import yaml
except Exception:  # pragma: no cover
    yaml = None  # type: ignore


# ─────────────────────────────────────────────────────────────────────────────
# Sub-configs
# ─────────────────────────────────────────────────────────────────────────────

@dataclass
class DataConfig:
    image_dir: str = "steeldefect_ssl/data/sample_images"   # generated by pool_builder if absent
    image_size: int = 64
    grayscale: bool = True
    to_rgb: bool = False                  # True only for resnet18 / PatchCore baselines
    n_total_unlabeled: int = 4500         # long-tail pretraining pool (STEELDEFECT_CLASS_PRIOR)
    n_labeled_per_class: int = 40         # known labeled subset (probes / open-set fit / GCD anchors)
    n_eval_per_class: int = 30            # held-out test split for probes
    # held out of pretrain + known; injected into stream + GCD as the NOVEL families.
    # A range (distinct texture / blotch / edge) so the open-set eval isn't one cherry-picked class.
    novel_classes: list = field(default_factory=lambda: ["orange_peel", "scale", "edge_crack"])
    stream_n: int = 2000                  # open-set evaluation stream (known + novel mix); synthetic only
    novel_frac_in_stream: float = 0.15    # fraction of the stream that is the novel family
    seed: int = 42
    regenerate: bool = False              # force re-generation even if image_dir exists
    source: str = "synthetic"             # "synthetic" (build_pools) | "real" (load_real_pools, e.g. NEU-DET)


@dataclass
class EncoderConfig:
    arch: str = "ssl_resnet"              # ssl_resnet | resnet18
    embed_dim: int = 256                  # backbone output (256..512)
    proj_dim: int = 128                   # projection head output
    pred_dim: int = 64                    # SimSiam predictor bottleneck
    in_channels: int = 1
    width: int = 32                       # base channel width of SSLResNet stem


@dataclass
class SSLConfig:
    method: str = "simclr"                # simclr primary (empirically >> simsiam on this corpus)
    compare: bool = False                 # comparison run off for the long best-results run
    epochs: int = 70                      # SimCLR loss was still descending at 16 -> train properly
    batch_size: int = 256                 # more in-batch negatives -> stronger contrastive features
    lr: float = 0.05
    weight_decay: float = 1.0e-4
    momentum: float = 0.9
    temperature: float = 0.2              # NT-Xent (SimCLR) only
    num_workers: int = 0                  # 0 = Windows/CPU-safe (no spawn overhead)
    checkpoint: str = "steeldefect_ssl/outputs/steeldefect_ssl_encoder.pt"


@dataclass
class OpenSetConfig:
    scorer: str = "energy"                # mahalanobis | knn | cos_proto | energy
    knn_k: int = 5
    shrinkage: float = 1.0e-3             # covariance regularisation (PaDiM idiom)
    l2_normalize: bool = True             # score on L2-normalised features (SimCLR hypersphere geometry)
    run_patchcore_baseline: bool = False


@dataclass
class DiscoveryConfig:
    k_select: str = "gap"                 # gap | deep_dpm | fixed
    k_range: Tuple[int, int] = (8, 20)
    fixed_k: Optional[int] = None
    outlier_detection: bool = True
    outlier_contamination: float = 0.05


@dataclass
class ContinualConfig:
    metric: str = "ncm"                   # ncm (nearest-class-mean prototypes)
    replay_per_class: int = 0             # 0 = pure additive prototypes; >0 = herding buffer


@dataclass
class EvalConfig:
    knn_k: int = 10
    raw_pca_dim: int = 64
    bootstrap_n: int = 100
    known_k: int = 10                     # #known classes used for the clustering-uplift KMeans


@dataclass
class RuntimeConfig:
    seed: int = 42
    log_level: str = "INFO"
    fast_mode: bool = True                # smoke; flip off with --full
    device: str = "cpu"


@dataclass
class OutputConfig:
    dir: str = "steeldefect_ssl/outputs"
    plots_dir: str = "steeldefect_ssl/outputs/plots"
    reports_dir: str = "steeldefect_ssl/outputs/reports"
    clear_previous: bool = True


@dataclass
class SSLPipelineConfig:
    data: DataConfig = field(default_factory=DataConfig)
    encoder: EncoderConfig = field(default_factory=EncoderConfig)
    ssl: SSLConfig = field(default_factory=SSLConfig)
    openset: OpenSetConfig = field(default_factory=OpenSetConfig)
    discovery: DiscoveryConfig = field(default_factory=DiscoveryConfig)
    continual: ContinualConfig = field(default_factory=ContinualConfig)
    eval: EvalConfig = field(default_factory=EvalConfig)
    runtime: RuntimeConfig = field(default_factory=RuntimeConfig)
    output: OutputConfig = field(default_factory=OutputConfig)
    obt_table: str = "steeldefect.obt_segmentations"
    mlflow_model_name: str = "steeldefect_ssl_encoder"


# ─────────────────────────────────────────────────────────────────────────────
# (de)serialisation
# ─────────────────────────────────────────────────────────────────────────────

def _from_dict(dc_type, d: Dict[str, Any]):
    """Recursively build a (possibly nested) dataclass, rejecting unknown keys."""
    if not isinstance(d, dict):
        raise TypeError(f"Expected a mapping for {dc_type.__name__}, got {type(d).__name__}")
    field_map = {f.name: f for f in fields(dc_type)}
    unknown = set(d) - set(field_map)
    if unknown:
        raise ValueError(
            f"Unknown config key(s) for {dc_type.__name__}: {sorted(unknown)} "
            f"(valid: {sorted(field_map)})"
        )
    kwargs: Dict[str, Any] = {}
    for name, f in field_map.items():
        if name not in d:
            continue
        val = d[name]
        if is_dataclass(f.type) and isinstance(val, dict):
            kwargs[name] = _from_dict(f.type, val)
        elif name == "k_range" and isinstance(val, (list, tuple)):
            kwargs[name] = (int(val[0]), int(val[1]))
        else:
            kwargs[name] = val
    return dc_type(**kwargs)


def _to_dict(obj) -> Dict[str, Any]:
    if is_dataclass(obj):
        return {f.name: _to_dict(getattr(obj, f.name)) for f in fields(obj)}
    if isinstance(obj, tuple):
        return list(obj)
    return obj


def from_dict(d: Dict[str, Any]) -> SSLPipelineConfig:
    return _from_dict(SSLPipelineConfig, d or {})


def to_dict(cfg: SSLPipelineConfig) -> Dict[str, Any]:
    return _to_dict(cfg)


def load_config(path: Optional[str] = None) -> SSLPipelineConfig:
    """Load + validate a YAML config (or return defaults if ``path`` is None)."""
    if path is None:
        cfg = SSLPipelineConfig()
    else:
        if yaml is None:  # pragma: no cover
            raise RuntimeError("pyyaml is required to load a YAML config")
        with open(path, "r", encoding="utf-8") as fh:
            raw = yaml.safe_load(fh) or {}
        cfg = from_dict(raw)
    _validate(cfg)
    return cfg


def save_config(cfg: SSLPipelineConfig, path: str) -> None:  # pragma: no cover
    if yaml is None:
        raise RuntimeError("pyyaml is required to save a YAML config")
    with open(path, "w", encoding="utf-8") as fh:
        yaml.safe_dump(to_dict(cfg), fh, sort_keys=False, allow_unicode=True)


# ─────────────────────────────────────────────────────────────────────────────
# validation + fast-mode
# ─────────────────────────────────────────────────────────────────────────────

def _validate(cfg: SSLPipelineConfig) -> None:
    d, e, s = cfg.data, cfg.encoder, cfg.ssl
    if d.image_size < 16:
        raise ValueError("data.image_size must be >= 16")
    if d.n_labeled_per_class < 5:
        raise ValueError("data.n_labeled_per_class must be >= 5 (Mahalanobis estimable)")
    if not (0.0 < d.novel_frac_in_stream < 1.0):
        raise ValueError("data.novel_frac_in_stream must be in (0,1)")
    if not d.novel_classes or not isinstance(d.novel_classes, list):
        raise ValueError("data.novel_classes must be a non-empty list")
    if d.source not in ("synthetic", "real"):
        raise ValueError("data.source must be 'synthetic' or 'real'")
    if e.arch not in ("ssl_resnet", "resnet18"):
        raise ValueError("encoder.arch must be 'ssl_resnet' or 'resnet18'")
    if e.embed_dim < 32:
        raise ValueError("encoder.embed_dim must be >= 32")
    if s.method not in ("simsiam", "simclr"):
        raise ValueError("ssl.method must be 'simsiam' or 'simclr'")
    if s.epochs < 1 or s.batch_size < 2 or s.lr <= 0:
        raise ValueError("ssl.epochs>=1, batch_size>=2, lr>0 required")
    if not (0.0 < s.temperature < 1.0):
        raise ValueError("ssl.temperature must be in (0,1)")
    if cfg.openset.scorer not in ("mahalanobis", "knn", "cos_proto", "energy"):
        raise ValueError("openset.scorer must be mahalanobis|knn|cos_proto|energy")
    if cfg.discovery.k_select not in ("gap", "deep_dpm", "fixed"):
        raise ValueError("discovery.k_select must be gap|deep_dpm|fixed")
    lo, hi = cfg.discovery.k_range
    if not (1 < lo < hi):
        raise ValueError("discovery.k_range must satisfy 1 < lo < hi")


def apply_fast_mode(cfg: SSLPipelineConfig) -> SSLPipelineConfig:
    """Shrink the workload for a ~4-5 min CPU smoke run (mirrors P2's fast_mode)."""
    cfg.ssl.epochs = min(cfg.ssl.epochs, 5)
    cfg.ssl.compare = False                       # one method only in smoke
    cfg.data.n_total_unlabeled = min(cfg.data.n_total_unlabeled, 1500)
    cfg.data.stream_n = min(cfg.data.stream_n, 600)
    cfg.data.n_labeled_per_class = min(cfg.data.n_labeled_per_class, 25)
    cfg.eval.bootstrap_n = min(cfg.eval.bootstrap_n, 20)
    cfg.discovery.k_range = (6, 12)
    cfg.openset.run_patchcore_baseline = False    # the costliest optional piece
    return cfg
